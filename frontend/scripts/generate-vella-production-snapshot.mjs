import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import path from 'node:path'

const cwd = process.cwd()
const localFrontendRoot = path.join(cwd, 'frontend')
let frontendRoot = cwd
try {
  await readFile(path.join(frontendRoot, 'public', 'vella-production.html'), 'utf8')
} catch {
  frontendRoot = localFrontendRoot
}
const sourcePath = path.join(frontendRoot, 'public', 'vella-production.html')
const targetPath = path.join(frontendRoot, 'src', 'features', 'vella-parity', 'vellaProductionSnapshot.generated.ts')

const html = await readFile(sourcePath, 'utf8')
const hash = createHash('sha256').update(html).digest('hex')
const generatedAt = new Date().toISOString()
const contents = `// Generated by scripts/generate-vella-production-snapshot.mjs. Do not edit manually.
export const vellaProductionSnapshotHash = ${JSON.stringify(hash)}
export const vellaProductionSnapshotGeneratedAt = ${JSON.stringify(generatedAt)}
export const vellaProductionHtml = ${JSON.stringify(html)}
`

await mkdir(path.dirname(targetPath), { recursive: true })
await writeFile(targetPath, contents)
console.log(`Generated ${path.relative(frontendRoot, targetPath)} from public/vella-production.html (${hash})`)
